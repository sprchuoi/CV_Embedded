def zt_delay_operator() -> str:
    """Four samples, the same four one sample later, and the algebra."""
    n = np.arange(len(DELAY_RECORD))
    x = DELAY_RECORD
    delayed = np.concatenate(([0.0], x))          # z^-1 X(z), by construction
    m = np.arange(len(delayed))

    # the recursion that turns the delay into a division
    h = _impulse(A, 6)
    closed = np.array([(-A) ** k for k in range(6)])
    residual = float(np.max(np.abs(h - closed)))

    fig, axes = P.figure(height=8.0, nrows=2, hspace=0.58,
                         height_ratios=[0.80, 1.20])
    ax_rec, ax_alg = axes

    # --- top: the record and its one-sample delay ---------------------------
    _stems(ax_rec, n - 0.10, x, colour=P.ACCENT, label="x[n]")
    _stems(ax_rec, m + 0.10, delayed, colour=P.NOTE, label="$z^{-1}$ x[n]")
    for k, value in enumerate(x):
        if value != 0.0:
            ax_rec.text(k - 0.10, value + (0.12 if value > 0 else -0.14),
                        f"{value:.2f}", color=P.ACCENT, fontsize=8.6,
                        ha="center", va="bottom" if value > 0 else "top")
    ax_rec.text(1 + 0.10, 1.0 + 0.12, "1.00", color=P.NOTE, fontsize=8.6,
                ha="center")
    ax_rec.annotate("the same numbers, one step to the right",
                    xy=(2.18, 0.80), xytext=(2.45, 1.55), color=P.NOTE,
                    fontsize=9.0, ha="left", va="center",
                    arrowprops=dict(arrowstyle="->", color=P.NOTE, lw=1.0,
                                    shrinkA=2, shrinkB=4))
    ax_rec.set_xlim(-0.7, len(delayed) + 0.4)
    ax_rec.set_ylim(-1.05, 2.25)
    ax_rec.axhline(0.0, color=P.SOFT, lw=0.9, zorder=2)
    P.tidy(ax_rec, xlabel="sample index  n", ylabel="value",
           legend=["x[n]", "$z^{-1}$ x[n]"], legend_loc="upper left")
    P.title(ax_rec, "A delay is a multiplication by $z^{-1}$",
            subtitle="multiply the polynomial by $z^{-1}$ and every coefficient "
                     "moves one place right; the numbers are untouched")

    # --- bottom: the algebra the picture is worth ---------------------------
    ax_alg.axis("off")
    ax_alg.text(0.0, 1.00, "$x[n] = 1.0,\\ -0.5,\\ 0.75,\\ 0.25$",
                transform=ax_alg.transAxes, fontsize=10.2, color=P.INK,
                ha="left", va="top")
    ax_alg.text(0.0, 0.880, "$X(z) = " + _poly_text(x) + "$",
                transform=ax_alg.transAxes, fontsize=10.6, color=P.ACCENT,
                ha="left", va="top")
    ax_alg.text(0.0, 0.760, "$z^{-1}X(z) = " + _poly_text(delayed) + "$",
                transform=ax_alg.transAxes, fontsize=10.6, color=P.NOTE,
                ha="left", va="top")
    ax_alg.text(0.0, 0.620,
                "every $z^{-1}$ is one sample of delay, so a difference "
                "equation is a statement about polynomials",
                transform=ax_alg.transAxes, fontsize=9.2, color=P.MUTED,
                ha="left", va="top")
    ax_alg.text(0.0, 0.470, "$y[n] = x[n] - 0.9\\,y[n-1]$",
                transform=ax_alg.transAxes, fontsize=10.4, color=P.INK,
                ha="left", va="top")
    ax_alg.text(0.50, 0.470, "$Y(z) = X(z) - 0.9\\,z^{-1}Y(z)$",
                transform=ax_alg.transAxes, fontsize=10.4, color=P.INK,
                ha="left", va="top")
    ax_alg.text(0.0, 0.340,
                "$H(z) = Y(z)/X(z) = 1/(1 + 0.9\\,z^{-1}) = z/(z + 0.9)$",
                transform=ax_alg.transAxes, fontsize=10.6, color=P.WARN,
                ha="left", va="center")
    _footnote(ax_alg, 0.0, 0.030,
              "pole  z = -0.900        zero  z = 0.000\n"
              "h[0..5] = 1.000, -0.900, 0.810, -0.729, 0.656, -0.590\n"
              f"against (-0.9)^n: max difference {residual:.1e}",
              ha="left", va="bottom", size=8.2, mono=True)

    print("[zt-delay-operator] record " + ", ".join(f"{v:+.2f}" for v in x)
          + f": X(z) = {_poly_text(x)}")
    print(f"[zt-delay-operator] delayed: z^-1 X(z) = {_poly_text(delayed)}")
    print(f"[zt-delay-operator] H(z) = 1/(1 + {A} z^-1) = z/(z + {A}): pole "
          f"{POLE:+.3f}, zero 0.000")
    print(f"[zt-delay-operator] h[0..5] = {', '.join(f'{v:+.3f}' for v in h)}; "
          f"max |h - (-0.9)^n| = {residual:.3e}")
    return P.render(fig)


