def zt_pole_radius() -> str:
    """One pole at three radii: the response, its envelope, and its peak."""
    n = np.arange(RADIUS_N)
    signals = {r: _impulse(r, RADIUS_N) for r in RADII}
    peaks = {r: float(np.max(np.abs(signals[r]))) for r in RADII}
    ends = {r: float(signals[r][-1]) for r in RADII}
    slopes = {r: 20.0 * np.log10(r) for r in RADII}

    # the algebraic value on the circle at Nyquist, where the pole is nearest
    formula = {}
    for r in RADII:
        denom = 1.0 - r
        formula[r] = float("inf") if abs(denom) < 1.0e-15 else 1.0 / abs(denom)
    long_check = (0.9999 ** BOUNDARY_CHECK, 1.0001 ** BOUNDARY_CHECK)

    colours = {0.9: P.ACCENT, 1.0: P.OPTICAL, 1.1: P.WARN}
    fig, axes = P.figure(height=8.1, nrows=2, hspace=0.56,
                         height_ratios=[1.0, 0.95])
    fig.subplots_adjust(bottom=0.17)
    ax_time, ax_db = axes

    # --- top: the response, run from the recursion --------------------------
    ax_time.axhline(0.0, color=P.SOFT, lw=0.9, zorder=2)
    ax_time.plot(n, A ** n, color=P.ACCENT, lw=1.0, ls=(0, (3, 3)), zorder=2)
    ax_time.plot(n, -A ** n, color=P.ACCENT, lw=1.0, ls=(0, (3, 3)), zorder=2,
                 label="envelope $\\pm 0.9^n$")
    for r in RADII:
        ax_time.plot(n, signals[r], color=colours[r], lw=1.5, zorder=5,
                     label=f"r = {r:.1f}  (pole $z$ = {-r:+.1f})")
    ax_time.annotate("0.9^40 = 0.0148: invisible here",
                     xy=(31.0, 0.8), xytext=(14.0, 19.0), color=P.ACCENT_DARK,
                     fontsize=8.6, ha="left", va="center", zorder=9,
                     arrowprops=dict(arrowstyle="->", color=P.ACCENT_DARK,
                                     lw=1.0, shrinkA=2, shrinkB=3))
    ax_time.set_xlim(-0.8, RADIUS_N + 3.0)
    ax_time.set_ylim(-52.0, 52.0)
    P.tidy(ax_time, xlabel="sample index  n", ylabel="impulse response  h[n]",
           legend=["envelope $\\pm 0.9^n$", "r = 0.9  (pole $z$ = -0.9)",
                   "r = 1.0  (pole $z$ = -1.0)", "r = 1.1  (pole $z$ = -1.1)"],
           legend_loc="lower left")
    P.title(ax_time, "One pole, three radii, three different futures",
            subtitle="the recursion is y[n] = x[n] - r y[n-1], run on a single "
                     "unit impulse")

    # --- bottom: the same three, in dB, where the radius is a slope ---------
    ax_db.axhline(0.0, color=P.SOFT, lw=0.9, ls=(0, (2, 3)), zorder=2)
    for r in RADII:
        db = 20.0 * np.log10(np.maximum(np.abs(signals[r]), 1.0e-18))
        ax_db.plot(n, db, color=colours[r], lw=1.6, zorder=5,
                   label=f"r = {r:.1f}: {slopes[r]:+.3f} dB per sample")
    ax_db.annotate(f"{slopes[0.9]:+.3f} dB per sample",
                   xy=(28.0, 20.0 * np.log10(A ** 28.0)),
                   xytext=(3.0, -48.0), color=P.ACCENT_DARK, fontsize=8.6,
                   ha="left", va="center", zorder=9,
                   arrowprops=dict(arrowstyle="->", color=P.ACCENT_DARK, lw=1.0,
                                   shrinkA=2, shrinkB=3))
    ax_db.annotate("on the circle: neither",
                   xy=(34.0, 0.0), xytext=(37.5, 3.6), color=P.OPTICAL_DARK,
                   fontsize=8.6, ha="right", va="center", zorder=9,
                   arrowprops=dict(arrowstyle="->", color=P.OPTICAL_DARK, lw=1.0,
                                   shrinkA=2, shrinkB=3))
    fig.text(0.012, 0.095,
             "the formula at $\\omega = \\pi$:  "
             f"{formula[0.9]:.3f}  |  $\\infty$  |  {formula[1.1]:.3f}"
             "     (the same 10.000, and only one of them is a response)",
             fontsize=8.2, color=P.INK, ha="left", va="top")
    fig.text(0.012, 0.058,
             "peak |h| over 41 samples:  1.000  /  1.000  /  45.259"
             "     h[40]:  0.0148  /  1.0000  /  45.2593"
             "     r = 0.9 / 1.0 / 1.1",
             fontsize=8.2, color=P.INK, ha="left", va="top")
    fig.text(0.012, 0.021,
             f"the same boundary in a long record:  0.9999^{BOUNDARY_CHECK} = "
             f"{long_check[0]:.3f}   1.0001^{BOUNDARY_CHECK} = "
             f"{long_check[1]:.3f}",
             fontsize=8.2, color=P.MUTED, ha="left", va="top")
    ax_db.set_xlim(-0.8, RADIUS_N + 3.0)
    ax_db.set_ylim(-60.0, 40.0)
    P.tidy(ax_db, xlabel="sample index  n",
           ylabel="$20\\log_{10}|h[n]|$  (dB)",
           legend=["r = 0.9: -0.915 dB per sample",
                   "r = 1.0: 0.000 dB per sample",
                   "r = 1.1: +0.828 dB per sample"],
           legend_loc="upper left")
    P.title(ax_db, "The radius is the slope of the decay",
            subtitle="a straight line on this axis, and its sign is the side of "
                     "the circle the pole is on")

    print(f"[zt-pole-radius] radii {RADII}: peaks over {RADIUS_N} samples "
          f"{peaks[0.9]:.4f}, {peaks[1.0]:.4f}, {peaks[1.1]:.4f}; h[40] "
          f"{abs(ends[0.9]):.5f}, {abs(ends[1.0]):.5f}, {abs(ends[1.1]):.5f}")
    print(f"[zt-pole-radius] slope per sample: "
          f"{slopes[0.9]:+.4f}, {slopes[1.0]:+.4f}, {slopes[1.1]:+.4f} dB; "
          f"0.9^40 = {A ** 40:.5f}, 1.1^40 = {1.1 ** 40:.4f}")
    print(f"[zt-pole-radius] |1/(1 + r e^-jw)| at w = pi: "
          f"{formula[0.9]:.4f}, inf, {formula[1.1]:.4f}; long record "
          f"0.9999^{BOUNDARY_CHECK} = {long_check[0]:.5f}, "
          f"1.0001^{BOUNDARY_CHECK} = {long_check[1]:.5f}")
    return P.render(fig)


# --------------------------------------------------------------------------- #
# 6. what a zero does to magnitude, and what only phase can see
# --------------------------------------------------------------------------- #


def zt_zero_phase() -> str:
    """A zero inside and its reciprocal outside: same |H|, different phase."""
    w = _circle()
    inside = 1.0 - ZERO_IN * np.exp(-1.0j * w)
    outside = 1.0 - ZERO_OUT * np.exp(-1.0j * w)
    mag_in = np.abs(inside)
    mag_out = np.abs(outside)
    same = float(np.max(np.abs(mag_out / (ZERO_OUT * mag_in) - 1.0)))

    phase_in = np.unwrap(np.angle(inside))
    phase_out = np.unwrap(np.angle(outside))
    w_at = np.pi / 2.0
    inside_at = float(np.angle(1.0 - ZERO_IN * np.exp(-1.0j * w_at)))
    outside_at = float(np.angle(1.0 - ZERO_OUT * np.exp(-1.0j * w_at)))

    allpass = ((np.exp(-1.0j * w) - AP_POLE)
               / (1.0 - AP_POLE * np.exp(-1.0j * w)))
    ap_dev = float(np.max(np.abs(np.abs(allpass) - 1.0)))
    ap_phase = np.unwrap(np.angle(allpass))
    ap_at = float(np.angle((np.exp(-1.0j * w_at) - AP_POLE)
                           / (1.0 - AP_POLE * np.exp(-1.0j * w_at))))

    fig, axes = P.figure(height=8.0, nrows=2, ncols=2, hspace=0.60)
    fig.subplots_adjust(wspace=0.34)
    (ax_plane, ax_mag), (ax_phase, ax_ap) = axes
    wn = w / np.pi

    # --- the plane: two zeros, and the mirror pair an all-pass is -----------
    _plane(ax_plane, limit=2.25)
    _zero(ax_plane, complex(ZERO_IN, 0.0), label="zero 0.500")
    _zero(ax_plane, complex(ZERO_OUT, 0.0), label="zero 2.000")
    _pole(ax_plane, complex(AP_POLE, 0.0), label="pole 0.600")
    _zero(ax_plane, complex(AP_ZERO, 0.0), label="zero 1.667")
    ax_plane.set_xlabel("real part of $z$")
    ax_plane.set_ylabel("imaginary part of $z$")
    ax_plane.legend(loc="lower left", fontsize=7.8, frameon=False,
                    handletextpad=0.5, borderaxespad=0.2, ncol=2)
    P.title(ax_plane, "A zero and its reciprocal",
            subtitle="the pair at 0.5 and 2")

    # --- the magnitudes coincide -------------------------------------------
    ax_mag.plot(wn, mag_in, color=P.ACCENT, lw=2.4, alpha=0.6, zorder=4,
                label="zero at 0.5")
    ax_mag.plot(wn[::20], (mag_out / ZERO_OUT)[::20], "o", ms=4.0,
                color=P.OPTICAL, mec=P.PANEL, mew=0.7, ls="none", zorder=6,
                label="zero at 2, divided by 2")
    ax_mag.plot(wn, np.ones_like(wn), color=P.WARN, lw=1.8, ls=(0, (5, 3)),
                zorder=3, label="the all-pass")
    ax_mag.set_xlim(-1.0, 1.0)
    ax_mag.set_ylim(0.0, 2.05)
    P.tidy(ax_mag, xlabel="$\\omega/\\pi$", ylabel="magnitude",
           legend=["zero at 0.5", "zero at 2, divided by 2", "the all-pass"],
           legend_loc="lower right")
    _footnote(ax_mag, 0.02, 0.975,
              f"max |ratio - 1| = {same:.1e}\n"
              "magnitude cannot tell them apart",
              colour=P.INK, ha="left", va="top", size=8.0)
    P.title(ax_mag, "The magnitude is the same curve",
            subtitle="a gain of 2 and nothing else")

    # --- the phases differ --------------------------------------------------
    ax_phase.plot(wn, phase_in, color=P.ACCENT, lw=2.0, zorder=4)
    ax_phase.plot(wn, phase_out, color=P.OPTICAL, lw=2.0, zorder=4)
    ax_phase.axhline(0.0, color=P.SOFT, lw=0.9, zorder=2)
    ax_phase.axvline(0.5, color=P.RULE, lw=1.1, ls=(0, (3, 3)), zorder=2)
    ax_phase.plot([0.5, 0.5], [inside_at, outside_at], "o", ms=6.0,
                  color=P.INK, mec=P.PANEL, mew=1.0, zorder=8)
    ax_phase.annotate(f"{inside_at:.4f} rad", xy=(0.5, inside_at),
                      xytext=(0.58, -0.30), color=P.ACCENT_DARK, fontsize=8.6,
                      ha="left", va="center", zorder=9,
                      arrowprops=dict(arrowstyle="->", color=P.ACCENT_DARK,
                                      lw=1.0, shrinkA=2, shrinkB=3))
    ax_phase.annotate(f"{outside_at:.4f} rad", xy=(0.5, outside_at),
                      xytext=(0.60, 1.60), color=P.OPTICAL_DARK, fontsize=8.6,
                      ha="left", va="center", zorder=9,
                      arrowprops=dict(arrowstyle="->", color=P.OPTICAL_DARK,
                                      lw=1.0, shrinkA=2, shrinkB=3))
    ax_phase.text(-0.95, 0.55, "zero inside", color=P.ACCENT_DARK,
                  fontsize=8.6, ha="left", va="center", zorder=9)
    ax_phase.text(-0.95, 2.80, "zero outside", color=P.OPTICAL_DARK,
                  fontsize=8.6, ha="left", va="center", zorder=9)
    ax_phase.set_xlim(-1.0, 1.0)
    ax_phase.set_ylim(-0.5, 3.4)
    P.tidy(ax_phase, xlabel="$\\omega/\\pi$", ylabel="phase  (rad)")
    P.title(ax_phase, "The phase is not",
            subtitle="the same magnitude, two different phase curves")

    # --- the all-pass: unit magnitude, all phase ----------------------------
    ax_ap.plot(wn, ap_phase, color=P.WARN, lw=2.0, zorder=4)
    ax_ap.axhline(0.0, color=P.SOFT, lw=0.9, zorder=2)
    ax_ap.plot([0.5], [ap_at], "o", ms=6.0, color=P.INK, mec=P.PANEL,
               mew=1.0, zorder=8)
    ax_ap.annotate(f"{ap_at:.4f} rad", xy=(0.52, ap_at), xytext=(0.62, -1.55),
                   color=P.WARN, fontsize=8.6, ha="left", va="center",
                   zorder=9,
                   arrowprops=dict(arrowstyle="->", color=P.WARN, lw=1.0,
                                   shrinkA=2, shrinkB=3))
    ax_ap.set_xlim(-1.0, 1.0)
    ax_ap.set_ylim(-3.6, 3.6)
