def zt_walk_the_circle() -> str:
    """The gain as a ratio of distances, against the direct evaluation."""
    w = _circle()
    zero = complex(1.0, 0.0)
    pole = complex(POLE, 0.0)
    d_pole, d_zero = _distances(w, pole, zero)
    geometric = d_zero / d_pole
    direct = np.abs(_h2(w))
    difference = float(np.max(np.abs(geometric - direct)))

    # one point on the circle, and the two chords that set its gain
    w_at = np.pi / 2.0
    point = np.exp(1.0j * w_at)
    d_zero_at = float(np.abs(point - zero))
    d_pole_at = float(np.abs(point - pole))
    gain_at = d_zero_at / d_pole_at

    # three frequencies worth printing, and the argument that produces them
    marks = []
    for angle in (0.0, np.pi / 2.0, np.pi):
        p = np.exp(1.0j * angle)
        dz = float(np.abs(p - zero))
        dp = float(np.abs(p - pole))
        marks.append((angle, dz, dp, dz / dp,
                      float(np.abs(_h2(np.array([angle])))[0])))
    peak_db = 20.0 * np.log10(marks[2][3])

    fig, axes = P.figure(height=8.4, nrows=2, hspace=0.52,
                         height_ratios=[1.0, 1.0])
    ax_plane, ax_curve = axes

    # --- top: the plane, with the chords at one point -----------------------
    _plane(ax_plane, limit=1.95)
    _pole(ax_plane, pole, label="pole")
    _zero(ax_plane, zero, label="zero")
    ax_plane.text(-0.90, 0.18, "pole", color=P.WARN, fontsize=8.8,
                  ha="center", va="bottom", zorder=9)
    ax_plane.text(1.00, 0.18, "zero", color=P.OPTICAL, fontsize=8.8,
                  ha="center", va="bottom", zorder=9)
    ax_plane.plot([0.0, point.real], [0.0, point.imag], color=P.MUTED, lw=0.9,
                  ls=(0, (2, 3)), zorder=4)
    ax_plane.plot([point.real], [point.imag], "o", ms=8.0, color=P.ACCENT,
                  mec=P.PANEL, mew=1.2, zorder=9)
    ax_plane.text(0.0, 1.12, "$\\omega = \\pi/2$",
                  color=P.ACCENT, fontsize=9.0, ha="center", va="bottom",
                  zorder=9)
    ax_plane.plot([point.real, zero.real], [point.imag, zero.imag],
                  color=P.OPTICAL, lw=2.2, zorder=6)
    ax_plane.plot([point.real, pole.real], [point.imag, pole.imag],
                  color=P.WARN, lw=2.2, zorder=6)
    ax_plane.annotate(f"$d_{{zero}}$ = {d_zero_at:.5f}",
                      xy=(0.62, 0.62), xytext=(0.78, 1.22),
                      color=P.OPTICAL, fontsize=9.2, ha="left", va="center",
                      zorder=10,
                      arrowprops=dict(arrowstyle="->", color=P.OPTICAL, lw=1.0,
                                      shrinkA=2, shrinkB=2))
    ax_plane.annotate(f"$d_{{pole}}$ = {d_pole_at:.5f}",
                      xy=(-0.48, 0.52), xytext=(-1.88, 0.86),
                      color=P.WARN, fontsize=9.2, ha="left", va="center",
                      zorder=10,
                      arrowprops=dict(arrowstyle="->", color=P.WARN, lw=1.0,
                                      shrinkA=2, shrinkB=2))
    _footnote(ax_plane, 0.02, 0.04,
              f"gain here = $d_{{zero}}/d_{{pole}}$ = {gain_at:.5f}\n"
              f"direct $|H(e^{{j\\pi/2}})|$ = "
              f"{float(np.abs(_h2(np.array([w_at])))[0]):.5f}",
              colour=P.INK, ha="left", va="bottom", size=8.0)
    ax_plane.text(1.07, 0.92,
                  "   w     ratio   direct\n"
                  f" 0.000   {marks[0][3]:6.3f}   {marks[0][4]:6.3f}\n"
                  f" pi/2    {marks[1][3]:6.3f}   {marks[1][4]:6.3f}\n"
                  f" pi     {marks[2][3]:6.3f}   {marks[2][4]:6.3f}\n"
                  f"max |diff| = {difference:.1e}",
                  transform=ax_plane.transAxes, family="monospace",
                  fontsize=8.2, color=P.INK, ha="left", va="top", zorder=11,
                  linespacing=1.35,
                  bbox=dict(boxstyle="round,pad=0.38", facecolor=P.PANEL,
                            edgecolor=P.RULE_SOFT, linewidth=1.0))
    ax_plane.set_xlabel("real part of $z$")
    ax_plane.set_ylabel("imaginary part of $z$")
    P.title(ax_plane, "The gain is a ratio of two distances",
            subtitle="every point on the circle makes a triangle, and its two "
                     "sides are all a second-order system needs")

    # --- bottom: the two computations, over the whole circle ----------------
    f = w / (2.0 * np.pi) * FS
    ax_curve.plot(f, geometric, color=P.ACCENT, lw=2.6, alpha=0.55, zorder=4,
                  label="$d_{zero}/d_{pole}$, the product of distances")
    step = 25
    ax_curve.plot(f[::step], direct[::step], "o", ms=4.2, color=P.WARN,
                  mec=P.PANEL, mew=0.7, ls="none", zorder=6,
                  label="direct evaluation of $H(z)$ at $z = e^{j\\omega}$")
    for angle, dz, dp, ratio, _ in marks:
        ax_curve.plot([angle / (2.0 * np.pi) * FS], [ratio], "o", ms=7.0,
                      color=P.INK, mec=P.PANEL, mew=1.1, zorder=8)
    ax_curve.annotate(f"$\\omega = \\pi$: {marks[2][3]:.3f}  "
                      f"({peak_db:+.2f} dB)",
                      xy=(FS / 2.0 - 20.0, marks[2][3]),
                      xytext=(FS / 2.0 - 1500.0, marks[2][3] - 1.0),
                      color=P.INK, fontsize=9.0, ha="left", va="center",
                      zorder=9,
                      arrowprops=dict(arrowstyle="->", color=P.INK, lw=1.0,
                                      shrinkA=2, shrinkB=4))
    ax_curve.annotate("a zero on the circle is an exact null",
                      xy=(30.0, 0.20), xytext=(330.0, 4.2), color=P.OPTICAL,
                      fontsize=8.8, ha="left", va="center", zorder=9,
                      arrowprops=dict(arrowstyle="->", color=P.OPTICAL, lw=1.0,
                                      shrinkA=2, shrinkB=4))
    ax_curve.set_xlim(0.0, FS / 2.0)
    ax_curve.set_ylim(0.0, 23.5)
    P.tidy(ax_curve, xlabel="frequency  (Hz), one half of the circle",
           ylabel="$|H(e^{j\\omega})|$",
           legend=["$d_{zero}/d_{pole}$, the product of distances",
                   "direct evaluation of $H(z)$ at $z = e^{j\\omega}$"],
           legend_loc="upper left")
    P.title(ax_curve, "Two ways to compute one number, and they agree",
            subtitle="H(z) = (1 - $z^{-1}$)/(1 + 0.9 $z^{-1}$): y[n] = x[n] - "
                     "x[n-1] - 0.9 y[n-1]")

    print(f"[zt-walk-the-circle] zero +1.000, pole -0.900: at w = pi/2 the "
          f"distances are {d_zero_at:.6f} and {d_pole_at:.6f}, ratio "
          f"{gain_at:.6f}")
    for angle, dz, dp, ratio, direct_value in marks:
        print(f"[zt-walk-the-circle] w = {angle / np.pi:.2f}pi: d_zero = "
              f"{dz:.4f}, d_pole = {dp:.4f}, ratio = {ratio:.4f}, direct = "
              f"{direct_value:.4f}")
    print(f"[zt-walk-the-circle] max |ratio - direct| over {GRID:,} points = "
          f"{difference:.3e}; peak {marks[2][3]:.3f} = {peak_db:+.3f} dB")
    return P.render(fig)


