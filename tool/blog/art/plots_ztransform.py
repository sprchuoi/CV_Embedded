"""Computed figures for the z-transform chapter.

Six figures, in the order the article uses them:

    zt-delay-operator   a four-sample record, the same record one sample later,
                        both polynomials, and the difference equation of the
                        one-pole system it turns into
    zt-plane-and-circle the pole-zero plane: the unit circle, one pole, one
                        zero at the origin, eight points on the circle, and
                        the two distances that set the gain at DC and Nyquist
    zt-dft-is-sampled  one period of |H(e^jw)| with chapter 6's 64 bins on it,
                        and the measured convergence of the DFT of a truncated
                        impulse response to those same points
    zt-walk-the-circle  the magnitude as a product of distances against the
                        direct evaluation, with the two distances drawn at one
                        point on the circle
    zt-pole-radius      one pole at three radii: the impulse response, its
                        envelope in dB per sample, and the peak of each
    zt-zero-phase       two zeros at reciprocal radii with the same magnitude
                        and different phase, and the all-pass they are the
                        mirror pair of

Nothing here asserts a transfer function. Every number the chapter prints is
computed from a difference equation or from the rational expression in this
module, printed on the figure, and printed again to stdout under the figure's
name so a build log can be audited against the page.

Two systems, and only two, are used:

* **S1**, the chapter's system: ``y[n] = x[n] - 0.9 y[n-1]``, so
  ``H1(z) = 1 / (1 + 0.9 z^-1) = z / (z + 0.9)`` -- a pole at ``z = -0.9`` and
  a zero at the origin. Its impulse response is generated by running the
  recursion, never by quoting ``(-0.9)^n``; the two are compared instead.
* **S2**, the same pole with a zero added on the circle: differencing the input
  before the recursion, ``y[n] = x[n] - x[n-1] - 0.9 y[n-1]``, so
  ``H2(z) = (1 - z^-1) / (1 + 0.9 z^-1)``. It is the system the geometry
  figure needs, because both of its distances move as the point walks the
  circle.

The unit circle is the whole frequency axis: ``z = e^{jw}`` with ``w = 2*pi*f/fs``
in radians per sample, so one turn of the circle is ``fs`` hertz and the
frequency axis closes on itself. Every figure that draws a frequency axis uses
the chapter 6 record -- ``fs = 8 kHz``, ``N = 64`` -- so its bins are 125 Hz
apart and can be recognised in the sections either side of this one.

Every figure is deterministic: no randomness is used anywhere in this module,
and no wall-clock measurement is printed, so two builds of the same commit
produce the same SVG.
"""

from __future__ import annotations

import numpy as np

from . import plotstyle as P

# --------------------------------------------------------------------------- #
# shared conventions
# --------------------------------------------------------------------------- #

A = 0.9                     # the coefficient, and the pole's radius
POLE = -A                   # S1's pole: z = -0.9
FS = 8000.0                 # Hz, chapter 6's record
N_DFT = 64                  # bins in that record
HZ_PER_BIN = FS / N_DFT     # 125 Hz
N_WALK = 8                  # points on the plane, drawn sparse to be legible
GRID = 4001                 # samples of the circle for every continuous curve

# figure 1: the four-sample record, and the same record delayed by one
DELAY_RECORD = np.array([1.0, -0.5, 0.75, 0.25])

# figure 4: the three radii, one for each side of the boundary
RADII = (0.9, 1.0, 1.1)
RADIUS_N = 41               # samples of impulse response drawn
BOUNDARY_CHECK = 10_000     # the long-record comparison in the footnote

# figure 5: how long a truncation has to be before the DFT is H
TRUNCATIONS = tuple(range(4, 257))

# figure 6: the reciprocal zero pair and the all-pass built from it
ZERO_IN = 0.5
ZERO_OUT = 1.0 / ZERO_IN    # 2.0
AP_POLE = 0.6
AP_ZERO = 1.0 / AP_POLE     # 1.666...

# the optical landing place, for the footnote that closes figure 3
FDE_N = 512
FDE_FS = 128.0e9
FDE_EDGE_HZ = 32.0e9


# --------------------------------------------------------------------------- #
# local helpers
# --------------------------------------------------------------------------- #


def _circle(grid: int = GRID) -> np.ndarray:
    """``w`` from ``-pi`` to ``pi``, the angles the plane is parameterised by."""
    return np.linspace(-np.pi, np.pi, grid)


def _h1(w: np.ndarray) -> np.ndarray:
    """``H1(e^jw) = 1 / (1 + 0.9 e^-jw)``, evaluated directly."""
    return 1.0 / (1.0 + A * np.exp(-1.0j * w))


def _h2(w: np.ndarray) -> np.ndarray:
    """``H2(e^jw) = (1 - e^-jw) / (1 + 0.9 e^-jw)``, evaluated directly."""
    return (1.0 - np.exp(-1.0j * w)) / (1.0 + A * np.exp(-1.0j * w))


def _impulse(r: float, length: int) -> np.ndarray:
    """Run ``y[n] = x[n] - r y[n-1]`` on an impulse: the response, not a formula."""
    h = np.zeros(length)
    prev = 0.0
    for n in range(length):
        prev = (1.0 if n == 0 else 0.0) - r * prev
        h[n] = prev
    return h


def _distances(w: np.ndarray, p: complex, z: complex) -> tuple[np.ndarray, np.ndarray]:
    """``|e^jw - p|`` and ``|e^jw - z|``: the two distances the gain is made of."""
    point = np.exp(1.0j * w)
    return np.abs(point - p), np.abs(point - z)


def _poly_text(coeffs, *, digits: int = 3, var: str = "z") -> str:
    """``sum c_k z^-k`` as mathtext, built from the coefficients themselves."""
    parts: list[str] = []
    for k, c in enumerate(np.asarray(coeffs, dtype=float)):
        if k == 0:
            parts.append(f"{c:.{digits}f}")
            continue
        sign = "+" if c >= 0.0 else "-"
        parts.append(f" {sign} {abs(c):.{digits}f}\\,{var}^{{-{k}}}")
    return "".join(parts)


def _stems(ax, x, y, *, colour: str, label: str | None = None, ms: float = 4.2,
           lw: float = 1.3, zorder: int = 4) -> None:
    """A stem plot in the house style: a line from zero and a point on top."""
    ax.vlines(x, 0.0, y, color=colour, lw=lw, zorder=zorder)
    ax.plot(x, y, "o", ms=ms, color=colour, mec=P.PANEL, mew=0.8, ls="none",
            zorder=zorder + 1, label=label)


def _footnote(ax, x: float, y: float, text: str, *, colour: str = P.INK,
              size: float = 8.6, ha: str = "left", va: str = "top",
              mono: bool = False) -> None:
    """A round-cornered note inside the axes, the way every figure here does it."""
    ax.text(x, y, text, transform=ax.transAxes, color=colour, fontsize=size,
            ha=ha, va=va, zorder=11,
            family="monospace" if mono else "sans-serif", linespacing=1.35,
            bbox=dict(boxstyle="round,pad=0.38", facecolor=P.PANEL,
                      edgecolor=P.RULE_SOFT, linewidth=1.0))


def _plane(ax, *, limit: float = 1.9) -> None:
    """Set up the complex plane: unit circle, axes, equal aspect, no grid."""
    theta = np.linspace(0.0, 2.0 * np.pi, 721)
    ax.plot(np.cos(theta), np.sin(theta), color=P.RULE, lw=1.5, zorder=2)
    ax.axhline(0.0, color=P.SOFT, lw=0.9, zorder=3)
    ax.axvline(0.0, color=P.SOFT, lw=0.9, zorder=3)
    ax.set_xlim(-limit, limit)
    ax.set_ylim(-limit, limit)
    ax.set_aspect("equal")
    ax.set_anchor("N")
    ax.grid(False)


def _pole(ax, point: complex, *, label: str) -> None:
    """A pole: the marker the plane is read with."""
    ax.plot([point.real], [point.imag], marker="x", ms=10.0, mew=2.4,
            color=P.WARN, ls="none", zorder=8, label=label)


def _zero(ax, point: complex, *, label: str) -> None:
    """A zero: a circle the response dies at."""
    ax.plot([point.real], [point.imag], marker="o", ms=9.0, mfc=P.PANEL,
            mec=P.OPTICAL, mew=2.0, ls="none", zorder=8, label=label)


