def zt_plane_and_circle() -> str:
    """The plane with one pole, one zero, and eight points on the circle."""
    w8 = np.arange(N_WALK) * 2.0 * np.pi / N_WALK
    values = np.abs(_h1(w8))
    dc_distance = float(np.abs(1.0 - POLE))
    nyq_distance = float(np.abs(-1.0 - POLE))
    dc = float(np.abs(_h1(np.array([0.0])))[0])
    nyq = float(np.abs(_h1(np.array([np.pi])))[0])
    quarter = float(np.abs(_h1(np.array([np.pi / 4.0])))[0])
    mirrored = np.array([values[(N_WALK - k) % N_WALK] for k in range(N_WALK)])
    mirror = float(np.max(np.abs(values - mirrored)))
    hz = w8 / (2.0 * np.pi) * FS

    fig, axes = P.figure(height=5.3, ncols=2)
    fig.subplots_adjust(wspace=0.32)
    ax_plane, ax_vals = axes

    # --- left: the plane ----------------------------------------------------
    _plane(ax_plane, limit=1.95)
    _pole(ax_plane, complex(POLE, 0.0), label="pole at $z$ = -0.900")
    _zero(ax_plane, complex(0.0, 0.0), label="zero at $z$ = 0")
    ax_plane.plot(np.cos(w8), np.sin(w8), "o", ms=5.0, color=P.ACCENT,
                  mec=P.PANEL, mew=1.0, ls="none", zorder=7,
                  label="8 points on the circle")
    for k in (0, 2, 4, 6):
        angle = w8[k]
        ax_plane.annotate(f"k={k}", xy=(np.cos(angle), np.sin(angle)),
                          xytext=(1.14 * np.cos(angle), 1.14 * np.sin(angle)),
                          color=P.ACCENT, fontsize=8.6, ha="center",
                          va="center", zorder=9)
    ax_plane.annotate("", xy=(0.36, 1.32), xytext=(1.02, 0.98),
                      arrowprops=dict(arrowstyle="->", color=P.MUTED, lw=1.1,
                                      connectionstyle="arc3,rad=-0.25"))
    ax_plane.text(0.58, 1.42, "$\\omega$ increases", color=P.MUTED,
                  fontsize=8.8, ha="left", va="bottom", zorder=9)
    # the two distances the gain is read from
    ax_plane.plot([POLE, 1.0], [0.0, 0.0], color=P.ACCENT_DARK, lw=1.6,
                  zorder=6)
    ax_plane.plot([POLE, -1.0], [0.0, 0.0], color=P.WARN, lw=2.6, zorder=6)
    ax_plane.annotate(f"{dc_distance:.3f}", xy=(-0.05, 0.0), xytext=(-0.05, 0.16),
                      color=P.ACCENT_DARK, fontsize=9.0, ha="center",
                      va="bottom", zorder=9)
    ax_plane.annotate(f"{nyq_distance:.3f}", xy=(-0.95, 0.0),
                      xytext=(-0.72, -0.28), color=P.WARN, fontsize=9.0,
                      ha="center", va="top", zorder=9,
                      arrowprops=dict(arrowstyle="->", color=P.WARN, lw=1.0,
                                      shrinkA=0, shrinkB=1))
    ax_plane.set_xlabel("real part of $z$")
    ax_plane.set_ylabel("imaginary part of $z$")
    ax_plane.legend(loc="lower left", fontsize=8.0, frameon=False,
                    handletextpad=0.5, borderaxespad=0.2)
    P.title(ax_plane, "One pole, one zero, and the circle",
            subtitle="the pole's distance is the whole story")

    # --- right: the same circle, sampled eight times ------------------------
    _stems(ax_vals, np.arange(N_WALK), values, colour=P.ACCENT)
    ax_vals.plot([4], [values[4]], "o", ms=8.0, color=P.WARN, mec=P.PANEL,
                 mew=1.2, zorder=8)
    ax_vals.annotate(f"{values[4]:.3f}\n$z$ = -1, 4 kHz",
                     xy=(4.0, values[4]), xytext=(4.35, 8.4),
                     color=P.WARN, fontsize=8.8, ha="left", va="center",
                     zorder=9,
                     arrowprops=dict(arrowstyle="->", color=P.WARN, lw=1.0,
                                     shrinkA=2, shrinkB=4))
    _footnote(ax_vals, 0.015, 0.975,
              "   k      0      1      2      3      4\n"
              "  f/Hz    0   1000   2000   3000   4000\n"
              "  |H|  0.526  0.570  0.743  1.364 10.000",
              colour=P.INK, ha="left", va="top", size=8.0, mono=True)
    _footnote(ax_vals, 0.985, 0.045,
              f"|H[k]| = |H[{N_WALK}-k]| to {mirror:.1e}\n"
              "a real response has an even magnitude",
              colour=P.INK, ha="right", va="bottom", size=8.0)
    ax_vals.set_xlim(-0.6, N_WALK - 0.3)
    ax_vals.set_ylim(0.0, 11.6)
    ax_vals.set_xticks(range(N_WALK))
    P.tidy(ax_vals, xlabel="point on the circle  $k$  (of 8)",
           ylabel="$|H(e^{j\\omega})|$")
    P.title(ax_vals, "Eight points are an eight-point DFT grid",
            subtitle="every eighth bin of chapter 6's 64")

    print(f"[zt-plane-and-circle] pole {POLE:+.3f}, zero +0.000; |z-pole| at "
          f"z=1: {dc_distance:.4f} -> gain {dc:.4f}; at z=-1: "
          f"{nyq_distance:.4f} -> gain {nyq:.4f}")
    print(f"[zt-plane-and-circle] 8 points at w = k*pi/4: gains "
          f"{', '.join(f'{v:.4f}' for v in values)}; mirror residual "
          f"{mirror:.3e}; gain at pi/4 = {quarter:.4f}")
    print(f"[zt-plane-and-circle] 8 points are chapter 6's bins 0, 8, ..., 56: "
          f"{', '.join(f'{f:.0f}' for f in hz)} Hz at fs = {FS:.0f} Hz")
    return P.render(fig)


